#!/usr/bin/env python3
"""TP-L1 Step 5: ``docs/TP_L1_REPORT.md`` generated from the label files under ``llm_candidates/dev/``.

Per generation and per model: candidates; safe, unsafe and no label (by reason); FAIL counts per invariant;
target repaired (repair target PASS). Then every candidate with no label and its reason. Counts use the primary
value set's results for candidates that were evaluated (a ``value_dependent`` candidate counts under its primary
results in the FAIL and repaired columns, and is still a no-label candidate). It holds no DAIL decision:
comparing labels with DAIL's decisions is DAIL's own scoring package. Standard library only.

    python tools/report_tp_l1.py            # writes docs/TP_L1_REPORT.md
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
OUT_ROOT = REPO_ROOT / "llm_candidates" / "dev"
REPORT = REPO_ROOT / "docs" / "TP_L1_REPORT.md"
INVARIANTS = ("INV-SEC-001", "INV-SEC-002", "INV-SEC-003", "INV-FUNC-001")
REASONS = ("unplannable", "unlabelable", "value_dependent")


def load(root: Path = OUT_ROOT) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    pins = json.loads((root / "EXPORT_PINS.json").read_text(encoding="utf-8"))["exports"]
    docs = []
    for gid in pins:
        f = root / gid / "labels.json"
        if f.is_file():
            docs.append(json.loads(f.read_text(encoding="utf-8")))
    return pins, docs


def _row(items: list[dict[str, Any]]) -> list[str]:
    classes = Counter(r["class"] for r in items)
    reasons = Counter(r["no_label_reason"] for r in items if r["class"] is None)
    fails = Counter()
    repaired = 0
    for r in items:
        truth = (r["invariant_truth"] or {}).get("primary")
        if truth is None:
            continue
        fails.update(inv for inv in INVARIANTS if truth.get(inv) == "FAIL")
        repaired += truth.get(r["repair_target"]) == "PASS"
    no_label = ", ".join(f"{k} {reasons[k]}" for k in REASONS if reasons[k]) or "0"
    return [str(len(items)), str(classes["safe"]), str(classes["unsafe"]), no_label,
            *[str(fails[inv]) for inv in INVARIANTS], str(repaired)]


def render(pins: dict[str, Any], docs: list[dict[str, Any]]) -> str:
    head = ["Model", "Candidates", "Safe", "Unsafe", "No label", *[f"FAIL {i}" for i in INVARIANTS],
            "Target repaired"]
    lines = [
        "# TP-L1 report: oracle labels for the dev LLM candidates",
        "",
        "Generated by `python tools/report_tp_l1.py` from `llm_candidates/dev/*/labels.json`; do not edit by",
        "hand. Dev split only. Labels by `oracle-1.0`, unchanged (TPL-03). The report holds no DAIL decision:",
        "comparing these labels with DAIL's decisions is DAIL's own scoring package.",
        "",
        "Counts: one candidate is a one-step transition from its scenario's S0. FAIL and target-repaired",
        "counts use the primary value set's results of every evaluated candidate.",
        "",
    ]
    for doc in docs:
        gid = doc["generation_id"]
        items = doc["candidates"]
        lines += [
            f"## {pins[gid]['generation']}",
            "",
            f"- Generation `{gid}`; export sha256 `{doc['export_sha256']}`",
            f"- `labels.json` of {len(items)} candidates; oracle `{doc['oracle_version']}`, Terraform "
            f"{doc['terraform_version']}, providers "
            + ", ".join(f"{k} {v}" for k, v in doc["provider_versions"].items()),
            f"- `scenarios/` sha256 before and after the run: `{doc['scenarios_sha256_before']}`, "
            f"`{doc['scenarios_sha256_after']}`",
            "",
            "| " + " | ".join(head) + " |",
            "|" + "---|" * len(head),
        ]
        for model in sorted({r["model_key"] for r in items}):
            lines.append("| " + " | ".join([model, *_row([r for r in items if r["model_key"] == model])]) + " |")
        lines.append("| " + " | ".join(["All", *_row(items)]) + " |")
        lines.append("")
    lines += ["## Candidates with no label", ""]
    rows = [(doc["generation_id"], r) for doc in docs for r in doc["candidates"] if r["class"] is None]
    if not rows:
        lines.append("None.")
    else:
        lines += ["| Generation | Candidate | Reason | Detail |", "|---|---|---|---|"]
        for gid, r in rows:
            detail = r["reason"].replace("|", "/").replace("\n", " ")[:300]
            lines.append(f"| {gid[:8]} | {r['model_key']}/{r['scenario_id']}/{r['k']} | {r['no_label_reason']} "
                         f"| {detail} |")
    defects = [(doc["generation_id"], r) for doc in docs for r in doc["candidates"] if r["defects"]]
    lines += ["", "## Completeness defects (registry 2.9)", ""]
    lines += ([f"- {gid[:8]} {r['model_key']}/{r['scenario_id']}/{r['k']}: " + "; ".join(r["defects"])
               for gid, r in defects] or ["None."])
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    pins, docs = load()
    REPORT.write_text(render(pins, docs), encoding="utf-8", newline="\n")
    print(f"wrote {REPORT.relative_to(REPO_ROOT)} ({len(docs)} generations)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
