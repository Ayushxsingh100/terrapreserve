"""Render ``yield_report.md`` from the ``yield.json`` document built by measure_yield.py.

Prose here is fixed text; every number is read from the document, so the report
cannot drift from the measurement. Standard library only.
"""

from __future__ import annotations

CONDITIONS = {
    "F0": "all modules",
    "F1": "at least 1 managed resource of an `aws_` type",
    "F2": "at least 1 managed resource, and every managed resource type is in S",
    "F2a": "F2, and no data sources",
    "F2b": "F2, and no module calls (strict; see the notes)",
    "F2ab": "F2a and F2b",
    "F3": "F2, and contains both `aws_instance` and `aws_db_instance`",
    "F3ab": "F2ab and F3",
    "F4": "F3, and contains `aws_security_group` or `aws_security_group_rule`",
    "G": "graft hosts: F2, not F3, and at least one of `aws_security_group`, `aws_security_group_rule`, `aws_subnet`",
    "X": "context: any types, contains both `aws_instance` and `aws_db_instance` (managed)",
}
BUCKETS = ("permissive", "weak copyleft", "strong copyleft", "other/unknown")
REAL_WORLD_SLOTS = 160  # 8 families x 20 (D0 Decision 3, as quoted in the D1 Prompt B)


def _n(value: int) -> str:
    return f"{value:,}"


def render(doc: dict) -> str:
    funnel = doc["funnel"]
    pin = doc.get("pin") or {}
    lines: list[str] = ["# TerraDS yield report", ""]
    lines += [
        "Generated by `sources/terrads/measure_yield.py` from the pinned `TerraDS.sqlite`. "
        "Every number below was computed by that script; nothing is assumed or padded.",
        "",
        f"- TerraDS Zenodo record: `{pin.get('record_id', 'not yet established')}`, "
        f"version DOI `{pin.get('doi', 'not yet established')}`, "
        f"concept DOI `{pin.get('concept_doi', 'not yet established')}`",
        f"- database sha256: `{pin.get('sqlite_sha256', 'not yet established')}`",
        f"- run (UTC): {doc['run_utc']}",
        f"- random seed reserved for the cross-check sample: {doc['seed']} "
        f"({'used' if (doc.get('crosscheck') or {}).get('status') in ('OK', 'PARTIAL') else 'not used: the cross-check did not run'})",
        "",
        "## How TerraDS defines its terms",
        "",
        "Read from the tools snapshot `HCL Dataset Tools.zip` (inspected in the cache), not assumed:",
        "",
        "- **Module**: a directory that directly contains at least one `*.tf` file "
        "(`src/repository_analyzer/processing.go`, `moduleDirectories`; `.tf.json` files are not matched). "
        "Each such directory is loaded with `tfconfig.LoadModule` from HashiCorp's "
        "terraform-config-inspect (module `github.com/hashicorp/terraform-config-inspect`, "
        "version `v0.0.0-20240801114854-6714b46f5fe4` in `go.mod`). One row per directory in `Modules`; "
        "subdirectories are separate modules.",
        "- **Resource types**: `module.ManagedResources` and `module.DataResources` from that call, one row "
        "per `type.name` in `Resources` (`ResourceType` is `Managed` or `Data`). A resource created with "
        "`count` or `for_each` is one row. Resources the inspector could not read are absent; the module's "
        "`DiagnosticMessages` is set when the inspector reported errors.",
        "- **Module calls**: `module.ModuleCalls`, stored as JSON `[{name, source}]` in `Modules.ModuleCalls`.",
        "- **Licence**: the GitHub API `license.spdx_id` of the repository at search time "
        "(`RepositorySearcher/GitHub/Repository.cs`), stored in `Repositories.License`. It is `null` when "
        "GitHub reports none. Only repositories whose licence is neither null nor `NOASSERTION` "
        "(view `RedistributableRepositories`) were cloned and analysed.",
        "- **Archive**: `dataset_cleaner/clean-repos.py` deletes every file that does not end in `.tf`, "
        "then empty folders. Licence files are therefore not expected in the archive.",
        "",
        "**Consequence for the cross-check.** TerraDS's own analyser is terraform-config-inspect, so an "
        "inspector run is the same tool that produced the metadata, not an independent parser (see the "
        "cross-check section).",
        "",
        "## Funnel",
        "",
        "S = the nine supported types plus `aws_db_subnet_group` (C-67). Counts are modules and distinct repositories.",
        "",
        "| Level | Condition | Modules | Repositories |",
        "|---|---|---:|---:|",
    ]
    for level, cond in CONDITIONS.items():
        lines.append(f"| {level} | {cond} | {_n(funnel[level]['modules'])} | {_n(funnel[level]['repos'])} |")
    lines += [
        "",
        "Notes on the definitions:",
        "",
        f"- F2b is strict: a module with any `module` block is excluded. If only calls whose source is not a "
        f"local path (`./` or `../`) were excluded, {_n(doc['f2b_nonlocal_calls_only'])} F2 modules would pass instead of "
        f"{_n(funnel['F2b']['modules'])}.",
        f"- {_n(doc['f2_modules_with_diagnostics'])} of the {_n(funnel['F2']['modules'])} F2 modules have "
        "non-empty `DiagnosticMessages`, so their resource lists may be incomplete. They are kept in the funnel "
        "and flagged in `candidates.csv` (`has_diagnostics`).",
        f"- {_n(doc['f2_modules_in_repos_missing_from_repositories_table'])} F2 modules belong to a repository id that is absent from "
        "`Repositories` (they count as licence `other/unknown`).",
        "",
        "## Database counts against the published figures",
        "",
    ]
    counts = doc["table_row_counts"]
    lines += [
        "| Quantity | Measured |",
        "|---|---:|",
        f"| rows in `Repositories` | {_n(counts.get('Repositories', 0))} |",
        f"| distinct repositories that have at least one module | {_n(doc['distinct_repositories_with_modules'])} |",
        f"| rows in `Modules` | {_n(counts.get('Modules', 0))} |",
        f"| rows in `Resources` | {_n(counts.get('Resources', 0))} |",
        f"| managed resources | {_n(doc['managed_resources'])} |",
        f"| data resources | {_n(doc['data_resources'])} |",
        "",
    ]
    for note in doc.get("published_comparison", []):
        lines.append(f"- {note}")
    if doc.get("published_comparison"):
        lines.append("")

    lines += ["## Licence buckets", ""]
    lines += [
        "Bucket rules: permissive = MIT, Apache-2.0, BSD-2-Clause, BSD-3-Clause, ISC, 0BSD, Unlicense, CC0-1.0, Zlib, "
        "**MIT-0, BSL-1.0**; weak copyleft = MPL-2.0, LGPL-\\*, EPL-\\*; strong copyleft = GPL-\\*, AGPL-\\*; "
        "everything else, including `NOASSERTION` and null, is other/unknown. Strings are stripped and compared "
        "case-insensitively before matching; nothing else is normalised.",
        "",
        "**Reviewer-approved list change (Prompt B review, R1):** `MIT-0` and `BSL-1.0` were added to the permissive "
        "list because both are OSI-approved and permit modification and redistribution. The Prompt B list is shown "
        "as \"before\" below. Whether copyleft repositories enter the pool is a D3 decision for the user; nothing "
        "here decides it.",
        "",
        "Erratum: an earlier version of the Prompt B report said the 152 F2 modules in other/unknown were all "
        "`Unlicense`. That was wrong. `Unlicense` (152 modules, 85 repositories) was already permissive; the 152 "
        "modules and 85 repositories in other/unknown were `MIT-0`, `CC-BY-SA-4.0`, `CC-BY-4.0`, `WTFPL`, `BSL-1.0` and "
        "`EUPL-1.2`, which happen to sum to the same two numbers.",
        "",
        "| Level | Bucket | Modules before | Repos before | Modules now | Repos now |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for level, per_bucket in doc["licence_buckets"].items():
        before = doc["licence_buckets_before_review"][level]
        for bucket in BUCKETS:
            cell, old = per_bucket[bucket], before[bucket]
            lines.append(
                f"| {level} | {bucket} | {_n(old['modules'])} | {_n(old['repos'])} | "
                f"{_n(cell['modules'])} | {_n(cell['repos'])} |"
            )
    lines += [
        "",
        "### Every distinct raw licence string",
        "",
        "`repr()` of the value stored in `Repositories.License`, so whitespace and case variants would show. "
        "Counts are modules / repositories.",
        "",
        "| `repr()` | Bucket now | Bucket before | Repos (whole dataset) | F2 | F3 | F3ab | G |",
        "|---|---|---|---:|---:|---:|---:|---:|",
    ]
    for e in doc["licence_inventory"]:
        cells = " | ".join(f"{_n(e[lv]['modules'])} / {_n(e[lv]['repos'])}" for lv in ("F2", "F3", "F3ab", "G"))
        lines.append(
            f"| `{e['repr']}` | {e['bucket']} | {e['bucket_before_review']} | {_n(e['repos_whole_dataset'])} | {cells} |"
        )
    lines += [
        "",
        "Strings that match no list and therefore stay **other/unknown**: "
        + ", ".join(f"`{x}`" for x in doc["licence_unmatched"])
        + ".",
        "",
    ]

    view = doc.get("redistributable_view") or {"present": False}
    lines += ["## The `RedistributableRepositories` view (report only)", ""]
    if view["present"]:
        has_efm = "_EFMigrationHistory" in doc["table_row_counts"]
        lines += [
            "Nothing in the funnel is filtered by this view.",
            "",
            "Definition, read from `sqlite_master`:",
            "",
            "```sql",
            view["sql"],
            "```",
            "",
            f"The view has {_n(view['rows_in_view'])} rows; `Repositories` has {_n(view['rows_in_repositories'])}.",
            "",
            "The tools snapshot's `README.md` says, in its list of steps to reproduce TerraDS:",
            "",
        ]
        lines += [f"> {x}" for x in view["tools_readme_lines"]] or ["> (no line mentions the view)"]
        lines += [
            "",
            "That is, the authors' README says the view (which it calls a table) should have been deleted before "
            "release; the pinned database still contains it. It also names `_EFMigrationHistory`; "
            + ("the pinned database still contains it." if has_efm else "the pinned database contains no such table."),
            "",
            "Repositories with at least one module in the level, by licence bucket and membership of the view:",
            "",
            "| Level | Bucket | In view: yes | In view: no |",
            "|---|---|---:|---:|",
        ]
        for level, per_bucket in view["crosstab_repositories"].items():
            for bucket in BUCKETS:
                cell = per_bucket[bucket]
                lines.append(f"| {level} | {bucket} | {_n(cell['in_view_yes'])} | {_n(cell['in_view_no'])} |")
        lines.append("")
    else:
        lines += ["The view is not present in the database.", ""]

    check = doc.get("crosscheck") or {"status": "UNRESOLVED", "reason": "not run"}
    lines += [f"## {check.get('title', 'Cross-check')}", ""]
    if check["status"] != "OK":
        lines += [f"**Status: {check['status']}**", "", check.get("reason", ""), ""]
    else:
        pop = check["population"]
        lines += [
            "TerraDS's metadata comes from terraform-config-inspect, so this check re-derives each sampled module's "
            "contents from its own files with a separate implementation (`sources/hcl_lex.py`, "
            "`sources/terrads/lexical_crosscheck.py`): stdlib only, no code shared with that analyser or with DAIL. "
            "Files are read in memory from `TerraDS.tar.gz`; nothing is written to disk.",
            "",
            f"- method: {check['method']}",
            f"- seed {check['seed']}; population: all {pop['F3']} F3 modules, plus {pop['F2_sample']} F2 modules "
            f"(`{pop['sampling']['F2_sample']}`; {pop['F3_in_F2_sample']} of them are also F3), "
            f"giving {pop['F3'] + pop['F2_sample'] - pop['F3_in_F2_sample']} distinct modules. "
            f"As an extra negative control, {pop['negative_control']} modules with an `aws_` resource that are not F2 "
            f"(`{pop['sampling']['negative_control']}`).",
            f"- files read: {_n(check['files_read']['.tf'])} `.tf`, {_n(check['files_read']['.tf.json'])} `.tf.json` "
            "(the archive holds only `.tf` files, see above, so the JSON reader is exercised by unit tests only)",
            f"- sampled modules with no file found in the archive: {check['modules_without_any_file_found']}; "
            f"modules where the lexer noted unbalanced braces or a malformed header: {check['modules_with_lexer_anomalies']} "
            f"({', '.join(str(i) for i in check.get('lexer_anomaly_module_ids', [])) or 'none'})",
            f"- development history: {check['development_history']}",
            "",
            "Agreement (modules that agree / modules compared):",
            "",
            "| Comparison | F3 | F2 sample | F3 + F2 sample | Negative control |",
            "|---|---:|---:|---:|---:|",
        ]
        names = {
            "types": "managed type set",
            "type_name_pairs": "managed (type, name) set",
            "has_data": "has data sources",
            "has_module_calls": "has module blocks",
            "is_F2": "F2 membership",
            "is_F3": "F3 membership",
        }
        agreement = check["agreement"]
        for key, label in names.items():
            cells = []
            for group in ("F3", "F2_sample", "positive_population_F3_union_F2_sample", "negative_control"):
                cell = agreement[group][key]
                cells.append(f"{cell['agree']}/{cell['total']} ({100 * cell['agree'] / cell['total']:.1f}%)")
            lines.append(f"| {label} | " + " | ".join(cells) + " |")
        lines += [
            "",
            "The F3 and F2-sample groups are chosen by TerraDS's own F2/F3 flags, so for them F2 and F3 agreement can "
            "only fail one way (the lexical reading says \"not F2\"). The negative control is the other direction: "
            "the lexical reading would have to say \"F2\" for a module TerraDS excluded.",
            "",
            f"### Disagreements ({check['disagreement_count']})",
            "",
            "| Module id | Group | Repository / path | Disagrees on | TerraDS types | Lexical types | Likely cause |",
            "|---|---|---|---|---|---|---|",
        ]
        for d in check["disagreements"]:
            lines.append(
                f"| {d['module_id']} | {', '.join(d['groups'])} | `{d['repo']}` `{d['path']}` | "
                f"{', '.join(d['disagrees_on'])} | {', '.join(f'`{t}`' for t in d['terrads_types']) or '-'} | "
                f"{', '.join(f'`{t}`' for t in d['lexical_types']) or '-'} | {d['likely_cause']} |"
            )
        lines += ["", f"terraform-config-inspect: {check['terraform_config_inspect']}", ""]

    scan = doc.get("archive_scan")
    lines += ["## Archive checks", ""]
    if scan:
        for row in scan["summary_lines"]:
            lines.append(f"- {row}")
        if not scan.get("f3_repositories_with_licence_file"):
            lines.append(
                "- The comparison of a licence file with the database's licence field could not be made for any F3 "
                "repository, because the archive holds no licence file (see the definition of the archive above)."
            )
    else:
        lines.append("Archive not scanned: `not yet established`.")
    lines.append("")

    lines += ["## What this means for D3 (arithmetic only)", ""]
    slots = REAL_WORLD_SLOTS
    lines += [
        f"The real-world slots are {slots} (8 families x 20, D0 Decision 3 as quoted in the Prompt B).",
        "",
        "| Pool | Modules | Repositories | Modules minus 160 | Repositories minus 160 |",
        "|---|---:|---:|---:|---:|",
    ]
    for level in ("F3", "F3ab", "F4"):
        if level in doc["licence_buckets"]:
            cell = doc["licence_buckets"][level]["permissive"]
            label = f"{level}, permissive"
        else:
            cell = funnel[level]
            label = f"{level}, all licences"
        lines.append(
            f"| {label} | {_n(cell['modules'])} | {_n(cell['repos'])} | "
            f"{cell['modules'] - slots:+,} | {cell['repos'] - slots:+,} |"
        )
    lines.append("")
    return "\n".join(lines)
