"""Render ``yield_report.md`` from the ``yield.json`` document built by measure_yield.py.

Prose here is fixed text; every number is read from the document, so the report
cannot drift from the measurement. Standard library only.
"""

from __future__ import annotations

CONDITIONS = {
    "F0": "all modules",
    "F1": "at least 1 managed resource of an `aws_` type",
    "F2": "at least 1 managed resource, and every managed resource type is in S",
    "F2a": "F2, and no data sources",
    "F2b": "F2, and no module calls (strict; see the notes)",
    "F2ab": "F2a and F2b",
    "F3": "F2, and contains both `aws_instance` and `aws_db_instance`",
    "F3ab": "F2ab and F3",
    "F4": "F3, and contains `aws_security_group` or `aws_security_group_rule`",
    "G": "graft hosts: F2, not F3, and at least one of `aws_security_group`, `aws_security_group_rule`, `aws_subnet`",
    "X": "context: any types, contains both `aws_instance` and `aws_db_instance` (managed)",
}
BUCKETS = ("permissive", "weak copyleft", "strong copyleft", "other/unknown")
REAL_WORLD_SLOTS = 160  # 8 families x 20 (D0 Decision 3, as quoted in the D1 Prompt B)


def _n(value: int) -> str:
    return f"{value:,}"


def render(doc: dict) -> str:
    funnel = doc["funnel"]
    pin = doc.get("pin") or {}
    lines: list[str] = ["# TerraDS yield report", ""]
    lines += [
        "Generated by `sources/terrads/measure_yield.py` from the pinned `TerraDS.sqlite`. "
        "Every number below was computed by that script; nothing is assumed or padded.",
        "",
        f"- TerraDS Zenodo record: `{pin.get('record_id', 'not yet established')}`, "
        f"version DOI `{pin.get('doi', 'not yet established')}`, "
        f"concept DOI `{pin.get('concept_doi', 'not yet established')}`",
        f"- database sha256: `{pin.get('sqlite_sha256', 'not yet established')}`",
        f"- run (UTC): {doc['run_utc']}",
        f"- random seed reserved for the cross-check sample: {doc['seed']} "
        f"({'used' if (doc.get('crosscheck') or {}).get('status') in ('OK', 'PARTIAL') else 'not used: the cross-check did not run'})",
        "",
        "## How TerraDS defines its terms",
        "",
        "Read from the tools snapshot `HCL Dataset Tools.zip` (inspected in the cache), not assumed:",
        "",
        "- **Module**: a directory that directly contains at least one `*.tf` file "
        "(`src/repository_analyzer/processing.go`, `moduleDirectories`; `.tf.json` files are not matched). "
        "Each such directory is loaded with `tfconfig.LoadModule` from HashiCorp's "
        "terraform-config-inspect (module `github.com/hashicorp/terraform-config-inspect`, "
        "version `v0.0.0-20240801114854-6714b46f5fe4` in `go.mod`). One row per directory in `Modules`; "
        "subdirectories are separate modules.",
        "- **Resource types**: `module.ManagedResources` and `module.DataResources` from that call, one row "
        "per `type.name` in `Resources` (`ResourceType` is `Managed` or `Data`). A resource created with "
        "`count` or `for_each` is one row. Resources the inspector could not read are absent; the module's "
        "`DiagnosticMessages` is set when the inspector reported errors.",
        "- **Module calls**: `module.ModuleCalls`, stored as JSON `[{name, source}]` in `Modules.ModuleCalls`.",
        "- **Licence**: the GitHub API `license.spdx_id` of the repository at search time "
        "(`RepositorySearcher/GitHub/Repository.cs`), stored in `Repositories.License`. It is `null` when "
        "GitHub reports none. Only repositories whose licence is neither null nor `NOASSERTION` "
        "(view `RedistributableRepositories`) were cloned and analysed.",
        "- **Archive**: `dataset_cleaner/clean-repos.py` deletes every file that does not end in `.tf`, "
        "then empty folders. Licence files are therefore not expected in the archive.",
        "",
        "**Consequence for the cross-check.** TerraDS's own analyser is terraform-config-inspect, so an "
        "inspector run is the same tool that produced the metadata, not an independent parser (see the "
        "cross-check section).",
        "",
        "## Funnel",
        "",
        "S = the nine supported types plus `aws_db_subnet_group` (C-67). Counts are modules and distinct repositories.",
        "",
        "| Level | Condition | Modules | Repositories |",
        "|---|---|---:|---:|",
    ]
    for level, cond in CONDITIONS.items():
        lines.append(f"| {level} | {cond} | {_n(funnel[level]['modules'])} | {_n(funnel[level]['repos'])} |")
    lines += [
        "",
        "Notes on the definitions:",
        "",
        f"- F2b is strict: a module with any `module` block is excluded. If only calls whose source is not a "
        f"local path (`./` or `../`) were excluded, {_n(doc['f2b_nonlocal_calls_only'])} F2 modules would pass instead of "
        f"{_n(funnel['F2b']['modules'])}.",
        f"- {_n(doc['f2_modules_with_diagnostics'])} of the {_n(funnel['F2']['modules'])} F2 modules have "
        "non-empty `DiagnosticMessages`, so their resource lists may be incomplete. They are kept in the funnel "
        "and flagged in `candidates.csv` (`has_diagnostics`).",
        f"- {_n(doc['f2_modules_in_repos_missing_from_repositories_table'])} F2 modules belong to a repository id that is absent from "
        "`Repositories` (they count as licence `other/unknown`).",
        "",
        "## Database counts against the published figures",
        "",
    ]
    counts = doc["table_row_counts"]
    lines += [
        "| Quantity | Measured |",
        "|---|---:|",
        f"| rows in `Repositories` | {_n(counts.get('Repositories', 0))} |",
        f"| distinct repositories that have at least one module | {_n(doc['distinct_repositories_with_modules'])} |",
        f"| rows in `Modules` | {_n(counts.get('Modules', 0))} |",
        f"| rows in `Resources` | {_n(counts.get('Resources', 0))} |",
        f"| managed resources | {_n(doc['managed_resources'])} |",
        f"| data resources | {_n(doc['data_resources'])} |",
        "",
    ]
    for note in doc.get("published_comparison", []):
        lines.append(f"- {note}")
    if doc.get("published_comparison"):
        lines.append("")

    lines += ["## Licence buckets", ""]
    lines += [
        "Bucket rules: permissive = MIT, Apache-2.0, BSD-2-Clause, BSD-3-Clause, ISC, 0BSD, Unlicense, CC0-1.0, Zlib; "
        "weak copyleft = MPL-2.0, LGPL-\\*, EPL-\\*; strong copyleft = GPL-\\*, AGPL-\\*; "
        "everything else, including `NOASSERTION` and null, is other/unknown. Whether copyleft repositories "
        "enter the pool is a D3 decision for the user; nothing here decides it.",
        "",
        "| Level | Bucket | Modules | Repositories |",
        "|---|---|---:|---:|",
    ]
    for level, per_bucket in doc["licence_buckets"].items():
        for bucket in BUCKETS:
            cell = per_bucket[bucket]
            lines.append(f"| {level} | {bucket} | {_n(cell['modules'])} | {_n(cell['repos'])} |")
    lines.append("")
    for level, per_licence in doc["licence_raw"].items():
        lines += [f"### Raw licence strings, {level}", "", "| Licence string | Modules | Repositories |", "|---|---:|---:|"]
        for name, cell in per_licence.items():
            lines.append(f"| `{name}` | {_n(cell['modules'])} | {_n(cell['repos'])} |")
        lines.append("")
    lines += [
        "### Whole-dataset licence strings (repositories)",
        "",
        "| Licence string | Repositories |",
        "|---|---:|",
    ]
    for name, count in doc["whole_dataset_repo_licences"].items():
        lines.append(f"| `{name}` | {_n(count)} |")
    lines.append("")

    lines += ["## Cross-check against terraform-config-inspect", ""]
    check = doc.get("crosscheck") or {"status": "UNRESOLVED", "reason": "not run"}
    lines.append(f"**Status: {check['status']}**")
    lines.append("")
    for key in ("reason", "error"):
        if check.get(key):
            lines += [check[key], ""]
    for key, label in (("tool_commit", "terraform-config-inspect commit"), ("go_version", "Go toolchain")):
        if check.get(key):
            lines.append(f"- {label}: `{check[key]}`")
    lines.append("")

    scan = doc.get("archive_scan")
    lines += ["## Archive checks", ""]
    if scan:
        for row in scan["summary_lines"]:
            lines.append(f"- {row}")
        if not scan.get("f3_repositories_with_licence_file"):
            lines.append(
                "- The comparison of a licence file with the database's licence field could not be made for any F3 "
                "repository, because the archive holds no licence file (see the definition of the archive above)."
            )
    else:
        lines.append("Archive not scanned: `not yet established`.")
    lines.append("")

    lines += ["## What this means for D3 (arithmetic only)", ""]
    slots = REAL_WORLD_SLOTS
    lines += [
        f"The real-world slots are {slots} (8 families x 20, D0 Decision 3 as quoted in the Prompt B).",
        "",
        "| Pool | Modules | Repositories | Modules minus 160 | Repositories minus 160 |",
        "|---|---:|---:|---:|---:|",
    ]
    for level in ("F3", "F3ab", "F4"):
        if level in doc["licence_buckets"]:
            cell = doc["licence_buckets"][level]["permissive"]
            label = f"{level}, permissive"
        else:
            cell = funnel[level]
            label = f"{level}, all licences"
        lines.append(
            f"| {label} | {_n(cell['modules'])} | {_n(cell['repos'])} | "
            f"{cell['modules'] - slots:+,} | {cell['repos'] - slots:+,} |"
        )
    lines.append("")
    return "\n".join(lines)
