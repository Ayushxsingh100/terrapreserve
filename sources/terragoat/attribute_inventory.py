"""Rule-independent inventory of credential-like attributes in TerraGoat (Prompt B review, R3).

    py -3.12 sources/terragoat/attribute_inventory.py

gitleaks is pattern-based, so "no finding" does not prove "no secret" (D0 gate 5).
This script flags every attribute in ``terraform/aws/*.tf`` (working tree at the pinned
commit) whose **name** matches ``password|passwd|secret|access_key|secret_key|token|
private_key|api_key|user_data|connection_string`` (case-insensitive, substring) and whose
**value is a literal**: a string with text outside ``${...}``, a heredoc, or a function
call that wraps one. References (``var.``, ``local.``, ``data.``, resource addresses) and
pure interpolations are not flagged but are counted.

It records file, line, resource address, block path and attribute name only. No value,
not even a fragment, is read into the output; the lexer keeps token kinds, not text.
The result replaces the section of ``secret_scan_summary.md`` that starts at
``SECTION_TITLE``.
"""

from __future__ import annotations

import collections
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import acquire  # noqa: E402
import hcl_lex  # noqa: E402

SUMMARY = acquire.REPO_ROOT / "sources" / "terragoat" / "secret_scan_summary.md"
SECTION_TITLE = "## Rule-independent attribute inventory"
NAME_RE = re.compile(
    r"password|passwd|secret|access_key|secret_key|token|private_key|api_key|user_data|connection_string",
    re.IGNORECASE,
)
FLAGGED_KINDS = ("literal", "heredoc", "call-with-literal")


def matching_attributes(text: str) -> list[hcl_lex.Attribute]:
    return [a for a in hcl_lex.attributes_from_hcl(text) if NAME_RE.search(a.name)]


def split_flagged(attrs: list[hcl_lex.Attribute]) -> tuple[list[hcl_lex.Attribute], list[hcl_lex.Attribute]]:
    flagged = [a for a in attrs if a.value_kind in FLAGGED_KINDS]
    return flagged, [a for a in attrs if a.value_kind not in FLAGGED_KINDS]


def overlaps(attr: hcl_lex.Attribute, findings: list[dict], rel: str) -> list[str]:
    """Rule ids of gitleaks findings in ``rel`` whose lines intersect the attribute's lines."""
    return sorted(
        {
            f["RuleID"]
            for f in findings
            if f["File"] == rel and f["StartLine"] <= attr.end_line and f["EndLine"] >= attr.line
        }
    )


def load_gitleaks(report: Path) -> list[dict]:
    """Findings under terraform/aws/, as (relative file, lines, rule id); nothing else is kept."""
    kept = []
    for f in json.loads(report.read_text(encoding="utf-8") or "[]"):
        path = f["File"].replace("\\", "/")
        if "terraform/aws/" in path:
            kept.append(
                {
                    "File": "terraform/aws/" + path.split("terraform/aws/", 1)[1],
                    "RuleID": f["RuleID"],
                    "StartLine": f["StartLine"],
                    "EndLine": f["EndLine"],
                }
            )
    return kept


def render(rows: list[dict], unflagged: collections.Counter, gitleaks: list[dict], matched_lines: set) -> str:
    by_name = collections.Counter(r["attribute"].lower() for r in rows)
    missed = collections.Counter(r["attribute"].lower() for r in rows if not r["gitleaks"])
    lines = [
        SECTION_TITLE,
        "",
        "Generated by `sources/terragoat/attribute_inventory.py`. gitleaks is pattern-based; this second inventory "
        "does not depend on its rules. It reads `terraform/aws/*.tf` at the pinned commit with the lexer in "
        "`sources/hcl_lex.py` and flags every attribute whose name matches (case-insensitive substring) "
        "`password|passwd|secret|access_key|secret_key|token|private_key|api_key|user_data|connection_string` "
        "and whose value is a literal: a string with text outside `${...}`, a heredoc, or a function call that "
        "wraps one. **Only file, line, resource address, block path and attribute name are recorded; no value, "
        "not even a fragment.** Files other than `*.tf` (the `resources/` folder holds a spreadsheet, a Dockerfile "
        "and a zip) are not covered by this inventory.",
        "",
        f"- flagged attributes: {len(rows)}",
        f"- not flagged although the name matches (reference or pure interpolation): {sum(unflagged.values())} "
        + (f"({', '.join(f'{k} {v}' for k, v in sorted(unflagged.items()))})" if unflagged else ""),
        f"- flagged and also covered by a gitleaks finding on the same lines: {sum(1 for r in rows if r['gitleaks'])}",
        f"- flagged but **not** covered by gitleaks: {sum(1 for r in rows if not r['gitleaks'])}",
        f"- gitleaks findings (working tree, `terraform/aws/`) that match none of these attributes: "
        f"{len([g for g in gitleaks if (g['File'], g['StartLine'], g['RuleID']) not in matched_lines])}",
        "",
        "| Attribute name | Flagged | Not covered by gitleaks |",
        "|---|---:|---:|",
    ]
    for name, count in sorted(by_name.items()):
        lines.append(f"| `{name}` | {count} | {missed.get(name, 0)} |")
    if not by_name:
        lines.append("| (none) | 0 | 0 |")
    lines += [
        "",
        "| File | Line | Resource address | Block path | Attribute | Value kind | gitleaks rule on these lines |",
        "|---|---:|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| `{r['file']}` | {r['line']} | `{r['address']}` | `{' / '.join(r['block_path'][1:]) or '-'}` | "
            f"`{r['attribute']}` | {r['kind']} | {', '.join(f'`{x}`' for x in r['gitleaks']) or '**none**'} |"
        )
    unmatched = [g for g in gitleaks if (g["File"], g["StartLine"], g["RuleID"]) not in matched_lines]
    if unmatched:
        lines += ["", "gitleaks findings not matched by the inventory (file, lines, rule only):", ""]
        lines += [f"- `{g['File']}` lines {g['StartLine']}-{g['EndLine']}, `{g['RuleID']}`" for g in unmatched]
    lines.append("")
    return "\n".join(lines)


def write_section(section: str) -> None:
    text = SUMMARY.read_text(encoding="utf-8")
    if SECTION_TITLE in text:
        text = text[: text.index(SECTION_TITLE)]
    SUMMARY.write_text(text.rstrip("\n") + "\n\n" + section, encoding="utf-8", newline="\n")


def main() -> int:
    try:
        root = acquire.cache_root()
        clone = root / "terragoat"
        manifest = acquire.load_manifest()
        pinned = acquire.entry_by_id(manifest, "terragoat")["commit"]
        head = acquire.git("rev-parse", "HEAD", cwd=clone)
        if head != pinned:
            raise acquire.AcquireError(f"clone is at {head}, manifest pins {pinned}")
        findings = load_gitleaks(root / "terragoat-scan" / "gitleaks-dir.json")
    except (acquire.AcquireError, OSError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    rows: list[dict] = []
    unflagged: collections.Counter = collections.Counter()
    matched: set = set()
    for path in sorted((clone / acquire.TERRAGOAT_SUBDIR).glob("*.tf")):
        rel = path.relative_to(clone).as_posix()
        flagged, rest = split_flagged(matching_attributes(path.read_text(encoding="utf-8", errors="replace")))
        unflagged.update(a.value_kind for a in rest)
        for a in flagged:
            rules = overlaps(a, findings, rel)
            matched.update((g["File"], g["StartLine"], g["RuleID"]) for g in findings
                           if g["File"] == rel and g["RuleID"] in rules and g["StartLine"] <= a.end_line and g["EndLine"] >= a.line)
            rows.append(
                {
                    "file": rel, "line": a.line, "address": a.top_level, "block_path": a.block_path,
                    "attribute": a.name, "kind": a.value_kind, "gitleaks": rules,
                }
            )
    write_section(render(rows, unflagged, findings, matched))
    print(f"flagged {len(rows)}; not covered by gitleaks {sum(1 for r in rows if not r['gitleaks'])}; "
          f"name matched but not flagged {dict(unflagged)}")
    by_name = collections.Counter(r["attribute"].lower() for r in rows)
    print(dict(sorted(by_name.items())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
