"""Diff TerraGoat's LICENSE against LICENSES/Apache-2.0.txt, whitespace-normalised (Prompt B review, R6).

    py -3.12 sources/terragoat/licence_diff.py

Both texts are split into whitespace-separated words, so line wrapping and
indentation are ignored. The differing stretches are listed with their position.
Licence text is Apache-2.0 boilerplate, not a secret; stretches are quoted in full.
"""

from __future__ import annotations

import difflib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import acquire  # noqa: E402

OUT = acquire.REPO_ROOT / "sources" / "terragoat" / "licence_diff.md"
REFERENCE = acquire.REPO_ROOT / "LICENSES" / "Apache-2.0.txt"


def compare(reference: str, other: str) -> list[tuple[str, int, int, str, str]]:
    """(tag, reference word offset, other word offset, reference words, other words) for each difference."""
    a, b = reference.split(), other.split()
    matcher = difflib.SequenceMatcher(None, a, b, autojunk=False)
    return [
        (tag, i1, j1, " ".join(a[i1:i2]), " ".join(b[j1:j2]))
        for tag, i1, i2, j1, j2 in matcher.get_opcodes()
        if tag != "equal"
    ]


def main() -> int:
    clone = acquire.cache_root() / "terragoat"
    other = (clone / "LICENSE").read_text(encoding="utf-8", errors="replace")
    reference = REFERENCE.read_text(encoding="utf-8")
    diffs = compare(reference, other)
    ref_words, other_words = len(reference.split()), len(other.split())
    lines = [
        "# TerraGoat LICENSE against LICENSES/Apache-2.0.txt",
        "",
        "Generated by `sources/terragoat/licence_diff.py`. Whitespace is normalised (words are compared), "
        "so wrapping and indentation do not count.",
        "",
        f"- words in `LICENSES/Apache-2.0.txt`: {ref_words:,}; words in TerraGoat's `LICENSE`: {other_words:,}",
        f"- differing stretches: {len(diffs)}",
        "",
    ]
    for n, (tag, i, j, ref_text, other_text) in enumerate(diffs, 1):
        lines += [
            f"## Difference {n} ({tag}; reference word {i:,} of {ref_words:,}, TerraGoat word {j:,} of {other_words:,})",
            "",
            f"- only in `LICENSES/Apache-2.0.txt`: {ref_text!r}" if ref_text else "- only in `LICENSES/Apache-2.0.txt`: nothing",
            f"- only in TerraGoat's `LICENSE`: {other_text!r}" if other_text else "- only in TerraGoat's `LICENSE`: nothing",
            "",
        ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(diffs)} differing stretches; words {ref_words} vs {other_words}")
    for tag, i, j, ref_text, other_text in diffs:
        print(tag, i, j, repr(ref_text[:300]), "->", repr(other_text[:600]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
