"""Scan the cached TerraGoat clone with gitleaks and write a value-free summary.

    py -3.12 sources/terragoat/scan_secrets.py <gitleaks-binary>

TerraGoat contains deliberate fake secrets (D0 gate 5). gitleaks always runs
with ``--redact``; the raw JSON report stays in the cache, and the committed
summary holds only the gitleaks version, counts per rule and file paths. D3
uses it to redact before anything enters ``pool/``.
"""

from __future__ import annotations

import collections
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import acquire  # noqa: E402  (sibling script, not a package)

SUMMARY = acquire.REPO_ROOT / "sources" / "terragoat" / "secret_scan_summary.md"
POOL_SOURCE = acquire.TERRAGOAT_SUBDIR + "/"


def run_gitleaks(binary: Path, mode: str, clone: Path, report: Path) -> list[dict]:
    """Run ``gitleaks dir`` or ``gitleaks git`` and return the findings (redacted)."""
    cmd = [
        str(binary), mode, ".",
        "--redact", "--no-banner", "--exit-code", "0",
        "--report-format", "json", "--report-path", str(report),
    ]
    # cwd=clone and path "." make gitleaks report paths relative to the repository root.
    result = subprocess.run(cmd, cwd=clone, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise acquire.AcquireError(f"gitleaks {mode} exited {result.returncode}: {result.stderr[-400:]}")
    findings = json.loads(report.read_text(encoding="utf-8") or "[]")
    for finding in findings:
        finding["File"] = finding["File"].replace("\\", "/").removeprefix("./")
    return findings


def render(version: str, commit: str, scans: dict[str, list[dict]]) -> str:
    """Markdown from rule ids and relative paths only; no field that can hold a value is read."""
    lines = [
        "# TerraGoat secret-scan summary",
        "",
        "Generated by `sources/terragoat/scan_secrets.py`. **No secret values appear here**: "
        "gitleaks ran with `--redact`, and only rule ids, file paths and counts are copied.",
        "",
        f"- gitleaks version: `{version}` (the version pinned in `.github/workflows/ci.yml`)",
        f"- TerraGoat commit: `{commit}`",
        "- D3 must redact the files listed below before anything enters `pool/` (D0 gate 5).",
        "",
    ]
    for mode, findings in scans.items():
        title = {"dir": "Working tree (`gitleaks dir`)", "git": "Git history (`gitleaks git`)"}[mode]
        in_pool = [f for f in findings if f["File"].startswith(POOL_SOURCE)]
        lines += [
            f"## {title}",
            "",
            f"- findings: {len(findings)}; under `{POOL_SOURCE}`: {len(in_pool)}",
            "",
            "| Rule | Findings | Under `terraform/aws/` |",
            "|---|---:|---:|",
        ]
        per_rule = collections.Counter(f["RuleID"] for f in findings)
        per_rule_pool = collections.Counter(f["RuleID"] for f in in_pool)
        for rule, count in sorted(per_rule.items()):
            lines.append(f"| `{rule}` | {count} | {per_rule_pool.get(rule, 0)} |")
        if not per_rule:
            lines.append("| (none) | 0 | 0 |")
        lines += ["", "| File | Rule | Findings |", "|---|---|---:|"]
        per_file = collections.Counter((f["File"], f["RuleID"]) for f in findings)
        for (path, rule), count in sorted(per_file.items()):
            lines.append(f"| `{path}` | `{rule}` | {count} |")
        if not per_file:
            lines.append("| (none) | | 0 |")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    binary = Path(argv[1])
    try:
        root = acquire.cache_root()
        clone = root / "terragoat"
        version = subprocess.run(
            [str(binary), "version"], capture_output=True, text=True, check=True
        ).stdout.strip()
        commit = acquire.git("rev-parse", "HEAD", cwd=clone)
        reports = root / "terragoat-scan"
        reports.mkdir(exist_ok=True)
        scans = {
            mode: run_gitleaks(binary, mode, clone, reports / f"gitleaks-{mode}.json")
            for mode in ("dir", "git")
        }
    except acquire.AcquireError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    SUMMARY.write_text(render(version, commit, scans), encoding="utf-8", newline="\n")
    for mode, findings in scans.items():
        print(f"{mode}: {len(findings)} findings")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
